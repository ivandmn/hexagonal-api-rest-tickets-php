<?php

declare(strict_types=1);

namespace App\Application\Command\CreateTask;

use App\Application\Command\CommandInterface;
use App\Application\Validation\Field;
use App\Domain\ValueObject\Task\TaskDescription;
use App\Domain\ValueObject\Task\TaskDueDate;
use App\Domain\ValueObject\Task\TaskId;
use App\Domain\ValueObject\Task\TaskPriority;
use App\Domain\ValueObject\Task\TaskTitle;

final readonly class CreateTaskCommand implements CommandInterface
{
    private TaskId $taskId;
    private TaskTitle $title;
    private TaskDescription $description;
    private TaskPriority $priority;
    private ?TaskDueDate $dueDate;

    /**
     * @param string $taskId generated by the sender, so it can read the task back afterwards
     */
    public function __construct(string $taskId, string $title, string $description, string $priority, ?string $dueDate)
    {
        $this->taskId      = Field::of('taskId', static fn (): TaskId => TaskId::fromString($taskId));
        $this->title       = Field::of('title', static fn (): TaskTitle => TaskTitle::fromString($title));
        $this->description = Field::of('description', static fn (): TaskDescription => TaskDescription::fromString($description));
        $this->priority    = Field::of('priority', static fn (): TaskPriority => TaskPriority::fromString($priority));
        $this->dueDate     = null !== $dueDate ? Field::of('dueDate', static fn (): TaskDueDate => TaskDueDate::fromString($dueDate)) : null;
    }

    public function getTaskId(): TaskId
    {
        return $this->taskId;
    }

    public function getTitle(): TaskTitle
    {
        return $this->title;
    }

    public function getDescription(): TaskDescription
    {
        return $this->description;
    }

    public function getPriority(): TaskPriority
    {
        return $this->priority;
    }

    public function getDueDate(): ?TaskDueDate
    {
        return $this->dueDate;
    }
}
